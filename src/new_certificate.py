"""Release-2 checks: complete 3-plane holonomy references and parity-constrained CCZ family.
Uses direct cubic polarization on truth tables, not the analytical rank arguments.
"""
from itertools import combinations, product, permutations
from collections import Counter
from fractions import Fraction
from algebra import basis, span, pol, monomial_comp

def planes(n,k):
    # Unique row-reduced echelon bases, leading bit at lowest occupied coordinate.
    for piv in combinations(range(n),k):
        free=[(i,j) for i,p in enumerate(piv) for j in range(p+1,n) if j not in piv]
        for bits in range(1<<len(free)):
            rows=[1<<p for p in piv]
            for l,(i,j) in enumerate(free):
                if bits>>l&1: rows[i]|=1<<j
            yield rows

def det(a,b,c):
    return sum(((a>>i)&1)*((b>>j)&1)*((c>>k)&1) for i,j,k in permutations(range(3)))%2

def rankhist(f):
    n=len(f).bit_length()-1;U=[1<<i for i in range(n)]
    # Form contraction matrices at basis vectors from complete truth table:
    # then use linearity in displacement. Each matrix row is a bit mask.
    matrices=[[sum(pol(f,a,b,c)<<j for j,c in enumerate(U)) for b in U] for a in U]
    rows=[0]*n;hist=Counter();last=0
    for i in range(1<<n):
        x=i^(i>>1);diff=x^last
        if diff:
            for j,y in enumerate(matrices[diff.bit_length()-1]): rows[j]^=y
        hist[len(basis(rows))]+=1;last=x
    return tuple(sorted(hist.items()))

def det_planes():
    hist=Counter();n=0
    for R in planes(6,3):
        S=span(R);f=[det(a,b&7,b>>3) for b in S for a in range(8)]
        h=rankhist(f);hist[h]+=1;n+=1
        if dict(h)[0]==1:assert h==((0,1),(2,7),(4,56))
        else:assert dict(h)[0]>=2
    assert n==1395
    print('h=2 determinant, every 3D reference R in F2^6:',n)
    for h,m in sorted(hist.items()):print('contraction ranks',h,'references',m)
    print('full nullity reference count',hist[((0,1),(2,7),(4,56))])
    # Four coordinate reference directions (in two charged columns), exact extraction by fixing spectator neutral coord.
    # Direct matching of matrix entries: choose a1 b2 c3 and a2 b3 c1; fix a3=0.
    for a1,a2,b2,b3,c1,c3 in product(range(2),repeat=6):
        assert det(a1|(a2<<1),(b2<<1)|(b3<<2),c1|(c3<<2))==(a1*b2*c3^a2*b3*c1)
    print('4D coordinate reference witnesses: 64 assignments')

def copy_family():
    for N in range(3,7):
        f=monomial_comp(3,N);h=dict(rankhist(f));assert h[0]==1 and h.get(2,0)==0
        print('fully charged N',N,'dimension',3*(N-1),'rank counts',h)
        # all 8 outcomes: choose x_N,3=s and x_{N-1},1=a,x_{N-1},2=b.
        # lower degree terms exactly s*x_N,1*x_N,2 + a*b*x_{N-1},3.
        for s,a,b in product(range(2),repeat=3):
            for mask in range(1<<(3*(N-2))):
                coords=[(mask>>(3*j))&7 for j in range(N-2)]
                tail=s
                for x in coords:tail^=x>>2
                vals=coords+[a|(b<<1)|(tail<<2)];last=0
                for x in vals:last^=x
                original=sum(x==7 for x in vals+[last])%2
                target=sum(x==7 for x in coords)%2
                correction=(s*(last&1)*((last>>1)&1))^(a*b*tail)
                assert original==target^correction
        print('N',N,'all branch identities checked',8*2**(3*(N-2)))
    # Exact reference budget generalized: R generated by standard final coordinates; dimensions 1 and 2
    for N in range(2,5):
        for ell in (1,2,3):
            k=3*(N-1)+ell;vals=[]
            for i in range(1<<k):
                x=[(i>>(3*j))&7 for j in range(N-1)];s=(i>>(3*(N-1)))<<(3-ell)
                for y in x:s^=y
                vals.append(sum(y==7 for y in x+[s])%2)
            h=dict(rankhist(vals));eta=k-(h[0].bit_length()-1)
            assert eta//3==(N-1 if ell<3 else N)
            print('reference N',N,'ell',ell,'eta',eta)
if __name__=='__main__':det_planes();copy_family()
